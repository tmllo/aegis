import { chromium } from '@playwright/test';
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const ctx = await b.newContext({ viewport: { width: 1920, height: 1080 } });
await ctx.addInitScript(() => { try { sessionStorage.setItem('ex-intro', '1'); } catch {} });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text().slice(0, 160)));
await p.goto('http://127.0.0.1:5630/', { waitUntil: 'load' }); await p.waitForTimeout(6000);
await p.click('button[aria-label="Enter a new sleep value"]');
await p.screenshot({ path: 'docs/shots/console/crew-edit.png' });
await p.fill('.vrow-edit input', '7.4'); await p.click('.vrow-edit button[type=submit]');
await p.waitForTimeout(1500);
console.log('word:', await p.textContent('.crew-word'), '| tips:', await p.locator('.tip').count());
await p.screenshot({ path: 'docs/shots/console/crew-edited.png' });
const q = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
await q.addInitScript(() => { try { sessionStorage.setItem('ex-intro', '1'); } catch {} });
const ph = await q.newPage(); await ph.goto('http://127.0.0.1:5630/', { waitUntil: 'load' }); await ph.waitForTimeout(6000);
console.log('phone hscroll:', await ph.evaluate(() => document.documentElement.scrollWidth > innerWidth));
await ph.screenshot({ path: 'docs/shots/console/phone-crew.png', fullPage: false });
console.log(errs.length ? errs : 'no errors'); await b.close();
