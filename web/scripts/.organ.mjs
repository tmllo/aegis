import { chromium } from '@playwright/test';
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const ctx = await b.newContext({ viewport: { width: 1920, height: 1080 } });
await ctx.addInitScript(() => { try { sessionStorage.setItem('ex-intro', '1'); } catch {} });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text().slice(0, 160)));
await p.goto('http://127.0.0.1:5630/?t=vessels&k=bp_sys', { waitUntil: 'load' }); await p.waitForTimeout(6000);
await p.screenshot({ path: 'docs/shots/console/organ-bp.png' });
await p.click('.rd-num');
for (let i = 0; i < 3; i++) await p.click('button[aria-label="Raise blood pressure, upper"]');
await p.screenshot({ path: 'docs/shots/console/organ-bp-edit.png' });
await p.goto('http://127.0.0.1:5630/?t=brain&k=sleep_h', { waitUntil: 'load' }); await p.waitForTimeout(5000);
console.log('before:', await p.textContent('.sheet-word'), '|', await p.textContent('.one-word'));
await p.click('.rd-num >> nth=0'); await p.fill('.rd-step input', '7.2'); await p.click('.rd-acts .solid'); await p.waitForTimeout(800);
console.log('after:', await p.textContent('.sheet-word'), '|', await p.textContent('.one-word'), '|', await p.textContent('.rd-name'));
await p.screenshot({ path: 'docs/shots/console/organ-brain-saved.png' });
console.log(errs.length ? errs : 'no errors'); await b.close();
